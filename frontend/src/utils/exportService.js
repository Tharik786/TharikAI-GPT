/**
 * Standard trigger to download blob in browser
 */
export function triggerDownload(blob, filename) {
  const url = window.URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => window.URL.revokeObjectURL(url), 1000);
}

/**
 * Download raw text or code file (e.g. script.py, index.html, styles.css)
 */
export function downloadTextFile(filename, content, mimeType = "text/plain;charset=utf-8") {
  const blob = new Blob([content], { type: mimeType });
  triggerDownload(blob, filename);
}

/**
 * Clean document text: strip web citation URLs, raw brackets, and template metadata
 */
export function cleanDocumentText(text) {
  if (!text) return "";
  return text
    // Remove markdown image tags ![alt](url)
    .replace(/!\[.*?\]\(.*?\)/g, "")
    // Remove web search citation links: [1](https://...), [2](https://...)
    .replace(/\[\d+\]\([^)]+\)/g, "")
    // Remove citation numbers in brackets: [1], [2], [12]
    .replace(/\[\d+\]/g, "")
    // Remove markdown links but preserve the readable anchor text: [Anchor](url) -> Anchor
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    // Remove standalone URLs
    .replace(/https?:\/\/[^\s)]+/g, "")
    // Remove template metadata lines
    .replace(/^(?:Executive\s+)?Document:\s*.*$/gim, "")
    .replace(/^Date:\s*.*$/gim, "")
    .replace(/^Prepared\s+by:\s*.*$/gim, "")
    .replace(/^Author:\s*.*$/gim, "")
    .replace(/^[-*_]{3,}$/gm, "")
    .trim();
}

/**
 * Clean markdown symbols for clean document text export
 */
export function cleanMarkdownForDoc(text) {
  if (!text) return "";
  return cleanDocumentText(text)
    .replace(/^#+\s+/gm, "") // remove heading hashes
    .replace(/\*\*(.+?)\*\*/g, "$1") // remove bold
    .replace(/\*(.+?)\*/g, "$1") // remove italics
    .replace(/`{3}[\s\S]*?`{3}/g, (match) => match.replace(/`{3}\w*\n?/g, "")) // clean code fences
    .replace(/`(.+?)`/g, "$1") // remove inline code ticks
    .trim();
}

/**
 * Build a structured, executive-styled PDF Document using jsPDF
 */
export function buildPdfDocument(title, content) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 18;
  const maxLineWidth = pageWidth - margin * 2; // ~174mm
  const cleanTitle = cleanDocumentText(title) || "Document";
  const cleanedContent = cleanDocumentText(content) || "";

  let curY = margin + 6;

  function checkPage(needHeight = 10) {
    if (curY + needHeight > pageHeight - margin - 8) {
      doc.addPage();
      curY = margin + 6;
      return true;
    }
    return false;
  }

  // Document Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(15, 23, 42); // #0F172A
  doc.text(cleanTitle, margin, curY);
  curY += 5;

  // Title underline accent (emerald #10B981)
  doc.setDrawColor(16, 185, 129);
  doc.setLineWidth(0.8);
  doc.line(margin, curY, margin + 45, curY);
  curY += 5;

  // Subtitle
  const dateStr = new Date().toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`Executive Document • Generated by TharikAI • ${dateStr}`, margin, curY);
  curY += 10;

  const lines = cleanedContent.replace(/\r\n/g, "\n").split("\n");
  let inCode = false;
  let codeBuffer = [];
  let tableRows = [];

  function flushPdfTable() {
    if (tableRows.length === 0) return;
    const isHeaderSeparator = (row) => row.every((c) => /^[-: ]+$/.test(c));
    const validRows = tableRows.filter((r) => !isHeaderSeparator(r));
    if (validRows.length > 0) {
      const numCols = Math.max(1, ...validRows.map((r) => r.length));
      const colWidth = maxLineWidth / numCols;
      const rowHeight = 7.5;

      checkPage(rowHeight * 2);

      validRows.forEach((row, rIdx) => {
        checkPage(rowHeight);
        const isHeader = rIdx === 0;

        // Background fill
        if (isHeader) {
          doc.setFillColor(15, 23, 42);
          doc.rect(margin, curY, maxLineWidth, rowHeight, "F");
        } else if (rIdx % 2 === 1) {
          doc.setFillColor(248, 250, 252);
          doc.rect(margin, curY, maxLineWidth, rowHeight, "F");
        }

        // Borders
        doc.setDrawColor(203, 213, 225);
        doc.setLineWidth(0.2);
        doc.rect(margin, curY, maxLineWidth, rowHeight, "S");

        // Text
        doc.setFont("helvetica", isHeader ? "bold" : "normal");
        doc.setFontSize(isHeader ? 9.5 : 9);
        doc.setTextColor(isHeader ? 255 : 30, isHeader ? 255 : 41, isHeader ? 255 : 59);

        row.forEach((cellText, cIdx) => {
          if (cIdx < numCols) {
            const cellClean = cellText.replace(/[*_`]/g, "").trim();
            const maxChars = Math.max(10, Math.floor(colWidth / 2.2));
            const display = cellClean.length > maxChars ? cellClean.slice(0, maxChars - 2) + ".." : cellClean;
            doc.text(display, margin + cIdx * colWidth + 2.5, curY + 5);
          }
        });

        curY += rowHeight;
      });

      curY += 4;
    }
    tableRows = [];
  }

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.trim();

    // Code blocks
    if (line.startsWith("```")) {
      if (inCode) {
        checkPage(codeBuffer.length * 4.5 + 8);
        const codeBoxH = codeBuffer.length * 4.5 + 6;
        doc.setFillColor(248, 250, 252);
        doc.rect(margin, curY, maxLineWidth, codeBoxH, "F");

        // Emerald left border
        doc.setDrawColor(16, 185, 129);
        doc.setLineWidth(1.0);
        doc.line(margin, curY, margin, curY + codeBoxH);

        doc.setFont("courier", "normal");
        doc.setFontSize(8.5);
        doc.setTextColor(15, 23, 42);

        let codeY = curY + 4;
        codeBuffer.forEach((cLine) => {
          doc.text(cLine.slice(0, 85) || " ", margin + 3, codeY);
          codeY += 4.5;
        });

        curY += codeBoxH + 4;
        codeBuffer = [];
        inCode = false;
      } else {
        flushPdfTable();
        inCode = true;
      }
      continue;
    }

    if (inCode) {
      codeBuffer.push(rawLine);
      continue;
    }

    // Markdown tables
    if (line.startsWith("|") && line.endsWith("|")) {
      const cells = line
        .split("|")
        .slice(1, -1)
        .map((s) => s.trim());
      tableRows.push(cells);
      continue;
    } else if (tableRows.length > 0) {
      flushPdfTable();
    }

    if (!line) continue;

    // Horizontal Rule
    if (/^[-*_]{3,}$/.test(line)) {
      checkPage(6);
      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.4);
      doc.line(margin, curY + 2, margin + maxLineWidth, curY + 2);
      curY += 6;
      continue;
    }

    // Headings
    if (line.startsWith("# ")) {
      const headingText = line.slice(2).trim().replace(/\*\*/g, "");
      if (headingText.toLowerCase() === cleanTitle.toLowerCase()) continue;
      checkPage(14);
      curY += 4;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(14.5);
      doc.setTextColor(15, 23, 42);
      doc.text(headingText, margin, curY);
      curY += 6.5;
    } else if (line.startsWith("## ")) {
      const headingText = line.slice(3).trim().replace(/\*\*/g, "");
      checkPage(12);
      curY += 3.5;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(12.5);
      doc.setTextColor(30, 41, 59);
      doc.text(headingText, margin, curY);
      curY += 5.5;
    } else if (line.startsWith("### ")) {
      const headingText = line.slice(4).trim().replace(/\*\*/g, "");
      checkPage(10);
      curY += 2.5;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(51, 65, 85);
      doc.text(headingText, margin, curY);
      curY += 5;
    } else if (/^[-*•]\s+/.test(line)) {
      const bulletText = line.replace(/^[-*•]\s+/, "").replace(/[*_`]/g, "").trim();
      checkPage(6);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(10);
      doc.setTextColor(16, 185, 129); // emerald bullet
      doc.text("•", margin + 1, curY);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(30, 41, 59);
      const splitBullet = doc.splitTextToSize(bulletText, maxLineWidth - 6);
      for (let bIdx = 0; bIdx < splitBullet.length; bIdx++) {
        if (bIdx > 0) checkPage(5);
        doc.text(splitBullet[bIdx], margin + 6, curY);
        curY += 5;
      }
      curY += 1;
    } else if (/^\d+\.\s+/.test(line)) {
      const numMatch = line.match(/^(\d+\.)\s+(.+)$/);
      const numPrefix = numMatch ? numMatch[1] : "";
      const numText = (numMatch ? numMatch[2] : line).replace(/[*_`]/g, "").trim();
      checkPage(6);

      doc.setFont("helvetica", "bold");
      doc.setFontSize(9.5);
      doc.setTextColor(16, 185, 129);
      doc.text(numPrefix, margin + 1, curY);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(30, 41, 59);
      const splitNum = doc.splitTextToSize(numText, maxLineWidth - 8);
      for (let nIdx = 0; nIdx < splitNum.length; nIdx++) {
        if (nIdx > 0) checkPage(5);
        doc.text(splitNum[nIdx], margin + 8, curY);
        curY += 5;
      }
      curY += 1;
    } else if (line.startsWith("> ")) {
      const quoteText = line.slice(2).replace(/[*_`]/g, "").trim();
      checkPage(8);
      doc.setDrawColor(16, 185, 129);
      doc.setLineWidth(0.8);
      doc.line(margin + 2, curY - 3, margin + 2, curY + 4);

      doc.setFont("helvetica", "italic");
      doc.setFontSize(9.5);
      doc.setTextColor(71, 85, 105);
      const splitQuote = doc.splitTextToSize(quoteText, maxLineWidth - 8);
      for (let qIdx = 0; qIdx < splitQuote.length; qIdx++) {
        if (qIdx > 0) checkPage(5);
        doc.text(splitQuote[qIdx], margin + 6, curY);
        curY += 5;
      }
      curY += 2;
    } else {
      const cleanPara = line.replace(/[*_`]/g, "").trim();
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(30, 41, 59);
      const splitPara = doc.splitTextToSize(cleanPara, maxLineWidth);
      for (const pLine of splitPara) {
        checkPage(5);
        doc.text(pLine, margin, curY);
        curY += 5;
      }
      curY += 2.5;
    }
  }

  flushPdfTable();

  // Clean page numbers
  const totalPages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Page ${i} of ${totalPages}`,
      pageWidth - margin,
      pageHeight - 10,
      { align: "right" }
    );
  }

  return doc;
}

