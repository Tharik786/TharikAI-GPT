/**
 * Robustly parses markdown tables or text into 2D rows
 */
export function parseMarkdownTableData(textOrMarkdown) {
  if (Array.isArray(textOrMarkdown)) return textOrMarkdown;
  if (!textOrMarkdown || typeof textOrMarkdown !== "string") return [];

  const rawLines = textOrMarkdown.trim().split("\n");
  const rows = [];
  let foundTable = false;

  for (const line of rawLines) {
    const trimmed = line.trim();
    if (!trimmed.includes("|")) continue;
    // Skip separator divider line like |---|---| or |:---:|
    if (/^\|?\s*[-:]+[-| :]*\|?$/.test(trimmed)) {
      foundTable = true;
      continue;
    }

    let content = trimmed;
    if (content.startsWith("|")) content = content.slice(1);
    if (content.endsWith("|")) content = content.slice(0, -1);

    const cols = content
      .split("|")
      .map((c) => cleanDocumentText(c.trim()).replace(/[*_`]/g, "").trim());

    if (cols.length > 0 && cols.some((c) => c.length > 0)) {
      rows.push(cols);
      foundTable = true;
    }
  }

  if (!foundTable || rows.length === 0) {
    const textLines = (textOrMarkdown || "").split("\n").filter((l) => l.trim());
    for (const l of textLines) {
      const cleaned = cleanDocumentText(l).replace(/[*_`#]/g, "").trim();
      if (cleaned) rows.push([cleaned]);
    }
  }

  return rows;
}

/**
 * Export tabular data or Markdown Table into Excel (.xlsx) / CSV
 */
export function exportTableToExcel(tableDataOrMarkdown, filename = "TharikAI_Data.xlsx") {
  try {
    const rows = parseMarkdownTableData(tableDataOrMarkdown);
    const ws = XLSX.utils.aoa_to_sheet(rows);

    // Auto-fit column widths so cell text is not truncated or hidden
    if (rows.length > 0 && rows[0].length > 0) {
      const colWidths = rows[0].map((_, colIdx) => {
        let maxLen = 14;
        rows.forEach((r) => {
          const val = r[colIdx] != null ? String(r[colIdx]) : "";
          if (val.length > maxLen) {
            maxLen = Math.min(val.length + 4, 50);
          }
        });
        return { wch: maxLen };
      });
      ws["!cols"] = colWidths;
    }

    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, "Sheet1");

    const finalName = filename.endsWith(".xlsx") ? filename : `${filename}.xlsx`;
    XLSX.writeFile(wb, finalName);
    return true;
  } catch (err) {
    console.error("Excel Export Error:", err);
    throw err;
  }
}

/**
 * Parse markdown inline formatting into docx TextRun elements
 */
function parseInlineFormatting(text, baseFont = "Segoe UI") {
  if (!text) return [];
  const runs = [];
  const regex = /(\*\*\*[\s\S]+?\*\*\*|\*\*[\s\S]+?\*\*|\*[\s\S]+?\*|___[\s\S]+?___|__[\s\S]+?__|`[\s\S]+?`|\[[\s\S]+?\]\([\s\S]+?\))/g;
  let lastIndex = 0;
  let match;

  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      runs.push(
        new TextRun({
          text: text.slice(lastIndex, match.index),
          font: baseFont,
          size: 22, // 11pt
          color: "1E293B",
        })
      );
    }
    const token = match[0];
    if (
      (token.startsWith("***") && token.endsWith("***")) ||
      (token.startsWith("___") && token.endsWith("___"))
    ) {
      runs.push(
        new TextRun({
          text: token.slice(3, -3),
          bold: true,
          italics: true,
          font: baseFont,
          size: 22,
          color: "0F172A",
        })
      );
    } else if (
      (token.startsWith("**") && token.endsWith("**")) ||
      (token.startsWith("__") && token.endsWith("__"))
    ) {
      runs.push(
        new TextRun({
          text: token.slice(2, -2),
          bold: true,
          font: baseFont,
          size: 22,
          color: "0F172A",
        })
      );
    } else if (token.startsWith("*") && token.endsWith("*")) {
      runs.push(
        new TextRun({
          text: token.slice(1, -1),
          italics: true,
          font: baseFont,
          size: 22,
          color: "334155",
        })
      );
    } else if (token.startsWith("`") && token.endsWith("`")) {
      runs.push(
        new TextRun({
          text: token.slice(1, -1),
          font: "Consolas",
          size: 20, // 10pt
          color: "0F172A",
          shading: { fill: "F1F5F9", type: ShadingType.CLEAR },
        })
      );
    } else if (token.startsWith("[") && token.includes("](")) {
      const linkMatch = token.match(/^\[([\s\S]*?)\]\(([\s\S]*?)\)$/);
      const label = linkMatch ? linkMatch[1] : token;
      runs.push(
        new TextRun({
          text: label,
          font: baseFont,
          size: 22,
          color: "0284C7",
          underline: {},
        })
      );
    }
    lastIndex = regex.lastIndex;
  }

  if (lastIndex < text.length) {
    runs.push(
      new TextRun({
        text: text.slice(lastIndex),
        font: baseFont,
        size: 22,
        color: "1E293B",
      })
    );
  }

  return runs.length > 0
    ? runs
    : [new TextRun({ text, font: baseFont, size: 22, color: "1E293B" })];
}

/**
 * Generate a genuine Microsoft Word (.docx) OpenXML binary Blob from markdown
 */
export async function generateWordDocxBlob(title, content) {
  const cleanTitle = cleanDocumentText(title) || "Document";
  const cleanedContent = cleanDocumentText(content) || "No content provided.";

  const children = [];

  // Document Title
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: cleanTitle,
          bold: true,
          font: "Segoe UI",
          size: 36, // 18pt
          color: "0F172A",
        }),
      ],
      spacing: { before: 120, after: 80 },
    })
  );

  // Subtitle / Brand header bar
  const dateStr = new Date().toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: `Executive Document • Generated by TharikAI • ${dateStr}`,
          font: "Segoe UI",
          size: 18, // 9pt
          color: "64748B",
        }),
      ],
      border: {
        bottom: { style: BorderStyle.SINGLE, size: 8, color: "10B981" },
      },
      spacing: { before: 0, after: 320 },
    })
  );

  const lines = cleanedContent.replace(/\r\n/g, "\n").split("\n");
  let inCode = false;
  let codeBuffer = [];
  let tableRows = [];

  function flushTable() {
    if (tableRows.length === 0) return;
    const docxRows = [];
    const isHeaderSeparator = (row) => row.every((c) => /^[-: ]+$/.test(c));

    let isHeader = true;
    for (let rIdx = 0; rIdx < tableRows.length; rIdx++) {
      const r = tableRows[rIdx];
      if (isHeaderSeparator(r)) {
        isHeader = false;
        continue;
      }
      const isHeaderRow = isHeader;
      const isAltRow = !isHeaderRow && rIdx % 2 === 1;

      const cells = r.map((c) => {
        return new TableCell({
          children: [
            new Paragraph({
              children: isHeaderRow
                ? [
                    new TextRun({
                      text: c,
                      bold: true,
                      color: "FFFFFF",
                      font: "Segoe UI",
                      size: 20, // 10pt
                    }),
                  ]
                : parseInlineFormatting(c),
              spacing: { before: 80, after: 80 },
            }),
          ],
          shading: isHeaderRow
            ? { fill: "0F172A", type: ShadingType.CLEAR }
            : isAltRow
            ? { fill: "F8FAFC", type: ShadingType.CLEAR }
            : undefined,
          borders: {
            top: { style: BorderStyle.SINGLE, size: 4, color: "CBD5E1" },
            bottom: { style: BorderStyle.SINGLE, size: 4, color: "CBD5E1" },
            left: { style: BorderStyle.SINGLE, size: 4, color: "CBD5E1" },
            right: { style: BorderStyle.SINGLE, size: 4, color: "CBD5E1" },
          },
          margins: {
            top: 100,
            bottom: 100,
            left: 140,
            right: 140,
          },
        });
      });

      docxRows.push(new TableRow({ children: cells }));
      isHeader = false;
    }

    if (docxRows.length > 0) {
      children.push(
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          rows: docxRows,
        })
      );
      children.push(new Paragraph({ text: "", spacing: { after: 140 } }));
    }
    tableRows = [];
  }

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.trim();

    // Code blocks
    if (line.startsWith("```")) {
      if (inCode) {
        children.push(
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({
                children: [
                  new TableCell({
                    shading: { fill: "F8FAFC", type: ShadingType.CLEAR },
                    borders: {
                      top: { style: BorderStyle.SINGLE, size: 4, color: "E2E8F0" },
                      bottom: { style: BorderStyle.SINGLE, size: 4, color: "E2E8F0" },
                      left: { style: BorderStyle.SINGLE, size: 16, color: "10B981" },
                      right: { style: BorderStyle.SINGLE, size: 4, color: "E2E8F0" },
                    },
                    margins: { top: 120, bottom: 120, left: 160, right: 160 },
                    children: codeBuffer.map(
                      (cLine) =>
                        new Paragraph({
                          children: [
                            new TextRun({
                              text: cLine || " ",
                              font: "Consolas",
                              size: 19,
                              color: "0F172A",
                            }),
                          ],
                          spacing: { before: 20, after: 20 },
                        })
                    ),
                  }),
                ],
              }),
            ],
          })
        );
        children.push(new Paragraph({ text: "", spacing: { after: 140 } }));
        codeBuffer = [];
        inCode = false;
      } else {
        flushTable();
        inCode = true;
      }
      continue;
    }

    if (inCode) {
      codeBuffer.push(rawLine);
      continue;
    }

    // Markdown tables
    if (line.startsWith("|") && line.endsWith("|")) {
      const cells = line
        .split("|")
        .slice(1, -1)
        .map((s) => s.trim());
      tableRows.push(cells);
      continue;
    } else if (tableRows.length > 0) {
      flushTable();
    }

    if (!line) {
      continue;
    }

    // Horizontal Rule
    if (/^[-*_]{3,}$/.test(line)) {
      children.push(
        new Paragraph({
          border: {
            bottom: { style: BorderStyle.SINGLE, size: 6, color: "E2E8F0" },
          },
          spacing: { before: 140, after: 140 },
        })
      );
      continue;
    }

    // Headings
    if (line.startsWith("# ")) {
      const headingText = line.slice(2).trim();
      // If heading equals the document title, skip duplicating the title
      if (headingText.toLowerCase() === cleanTitle.toLowerCase()) {
        continue;
      }
      children.push(
        new Paragraph({
          children: parseInlineFormatting(headingText),
          heading: HeadingLevel.HEADING_1,
          border: {
            bottom: { style: BorderStyle.SINGLE, size: 4, color: "10B981" },
          },
          spacing: { before: 280, after: 120 },
        })
      );
    } else if (line.startsWith("## ")) {
      children.push(
        new Paragraph({
          children: parseInlineFormatting(line.slice(3).trim()),
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 240, after: 100 },
        })
      );
    } else if (line.startsWith("### ")) {
      children.push(
        new Paragraph({
          children: parseInlineFormatting(line.slice(4).trim()),
          heading: HeadingLevel.HEADING_3,
          spacing: { before: 200, after: 80 },
        })
      );
    } else if (line.startsWith("#### ")) {
      children.push(
        new Paragraph({
          children: parseInlineFormatting(line.slice(5).trim()),
          heading: HeadingLevel.HEADING_4,
          spacing: { before: 160, after: 60 },
        })
      );
    } else if (/^[-*•]\s+/.test(line)) {
      const bulletText = line.replace(/^[-*•]\s+/, "").trim();
      children.push(
        new Paragraph({
          bullet: { level: 0 },
          children: parseInlineFormatting(bulletText),
          spacing: { before: 40, after: 40, line: 276 },
        })
      );
    } else if (/^\d+\.\s+/.test(line)) {
      const numMatch = line.match(/^(\d+\.)\s+(.+)$/);
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: `${numMatch[1]}  `,
              bold: true,
              font: "Segoe UI",
              size: 22,
              color: "10B981",
            }),
            ...parseInlineFormatting(numMatch[2]),
          ],
          spacing: { before: 40, after: 40, line: 276 },
        })
      );
    } else if (line.startsWith("> ")) {
      children.push(
        new Paragraph({
          children: parseInlineFormatting(line.slice(2).trim()),
          indent: { left: 400 },
          border: {
            left: { style: BorderStyle.SINGLE, size: 12, color: "10B981" },
          },
          spacing: { before: 100, after: 100, line: 276 },
        })
      );
    } else {
      children.push(
        new Paragraph({
          children: parseInlineFormatting(line),
          spacing: { before: 60, after: 120, line: 276 },
        })
      );
    }
  }

  flushTable();

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: 1440,
              bottom: 1440,
              left: 1440,
              right: 1440,
            },
          },
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.RIGHT,
                children: [
                  new TextRun({
                    text: "Page ",
                    font: "Segoe UI",
                    size: 18,
                    color: "94A3B8",
                  }),
                  new TextRun({
                    children: [PageNumber.CURRENT],
                    font: "Segoe UI",
                    size: 18,
                    color: "94A3B8",
                  }),
                  new TextRun({
                    text: " of ",
                    font: "Segoe UI",
                    size: 18,
                    color: "94A3B8",
                  }),
                  new TextRun({
                    children: [PageNumber.TOTAL_PAGES],
                    font: "Segoe UI",
                    size: 18,
                    color: "94A3B8",
                  }),
                ],
              }),
            ],
          }),
        },
        children,
      },
    ],
  });

  return await Packer.toBlob(doc);
}

